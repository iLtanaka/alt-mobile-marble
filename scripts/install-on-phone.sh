#!/bin/sh
# install-on-phone.sh <rootfs.tar.zst> [device]
#
# Runs as root ON THE PHONE while it is booted into postmarketOS. Installs an
# ALT Mobile root filesystem onto the spare partition (default: the GPT
# partition labelled "rootfs2"), copies the device specific kernel, modules,
# Device Tree and firmware out of postmarketOS, and creates the U-Boot entry.
#
# This is the step the old instructions were missing twice: without the modules
# and firmware the kernel panics or stays dark, and without /extlinux/others.env
# U-Boot has no "Other systems..." menu at all.

set -eu

TARBALL=${1:-}
DEV=${2:-/dev/disk/by-partlabel/rootfs2}
M=/mnt/marble-alt
ESP=/dev/disk/by-partlabel/esp

die() { echo "error: $*" >&2; exit 1; }
say() { echo "[alt-install] $*"; }

[ "$(id -u)" = 0 ] || die "run as root on the phone"
[ -n "$TARBALL" ] && [ -r "$TARBALL" ] || die "usage: $0 <rootfs.tar.zst> [device]"
. /etc/os-release
case ${ID:-} in
postmarketos|nura) ;;
*) die "this has to run on postmarketOS (running: ${ID:-unknown})" ;;
esac

DEV=$(readlink -f "$DEV") || die "no such partition"
[ -b "$DEV" ] || die "$DEV is not a block device"
[ "$(findmnt -no SOURCE /)" != "$DEV" ] || die "$DEV is the running root"
[ "$(findmnt -no SOURCE /boot)" = "$(readlink -f $ESP)" ] || die "/boot is not the esp partition"

PARTUUID=$(blkid -s PARTUUID -o value "$DEV") || die "no PARTUUID on $DEV"
ESPUUID=$(blkid -s UUID -o value $ESP) || die "no UUID on the esp"
KVER=$(uname -r)

# Wi-Fi: ath11k can report a zero MAC, so profiles get a fixed locally
# administered one. WIFI_MAC overrides; otherwise one is derived from this
# phone's machine-id so it is stable and differs between devices.
if [ -z "${WIFI_MAC:-}" ]; then
	h=$(md5sum </etc/machine-id | cut -c1-10)
	WIFI_MAC=$(echo "02$h" | sed 's/../&:/g; s/:$//')
fi

# Login password: random unless MP_PASS is set (sshd is enabled on the target).
if [ -z "${MP_PASS:-}" ]; then
	MP_PASS=$(tr -dc 'a-z0-9' </dev/urandom | head -c 10)
	GENERATED_PASS=1
fi

command -v mkfs.btrfs >/dev/null || die "mkfs.btrfs is missing; install btrfs-progs (apk add btrfs-progs)"
[ -r /boot/vmlinuz ] || die "no /boot/vmlinuz: is this a postmarketOS installation?"
[ -r /boot/sm8475-xiaomi-marble.dtb ] || die "no marble DTB in /boot"

say "kernel $KVER, target $DEV (PARTUUID $PARTUUID)"
say "this ERASES $DEV in 10 seconds, Ctrl-C to abort"
sleep 10

# --- 1. boot files on the esp ------------------------------------------------
# The kernel and DTB are copies: boot-deploy rewrites /boot/extlinux/extlinux.conf
# on every postmarketOS upgrade and must never see the ALT entry.
say "kernel, Device Tree and U-Boot entry"
mkdir -p /boot/alt
cp /boot/vmlinuz /boot/alt/vmlinuz && chmod 644 /boot/alt/vmlinuz
cp /boot/sm8475-xiaomi-marble.dtb /boot/alt/sm8475-xiaomi-marble.dtb && chmod 644 /boot/alt/sm8475-xiaomi-marble.dtb

cat > /boot/extlinux/alt.conf <<EOF
# marble-port: title=ALT Mobile Sisyphus
# Managed by alt-mobile-marble/scripts/install-on-phone.sh. The kernel and the
# DTB are copies from postmarketOS, so they keep matching the modules inside
# the ALT root filesystem even after a postmarketOS upgrade.
timeout 1
default alt

label alt
	kernel /alt/vmlinuz
	fdt /alt/sm8475-xiaomi-marble.dtb
	append root=PARTUUID=$PARTUUID rootfstype=btrfs rootflags=compress=zstd:3 rootwait rw console=tty0 loglevel=4 printk.devkmsg=on pstore.compress=none log_buf_len=2M msm_geni_serial.con_enabled=0 clk_ignore_unused pd_ignore_unused regulator_ignore_unused fw_devlink=permissive pcie_aspm=off
EOF

# U-Boot reads this file for the "Other systems..." submenu. Entries are
# rebuilt from every /extlinux/*.conf that carries a marble-port title line.
say "U-Boot \"Other systems...\" menu (/extlinux/others.env)"
{
	echo "# Generated by alt-mobile-marble/scripts/install-on-phone.sh"
	echo "# U-Boot \"Other systems...\" submenu; one entry per /extlinux/*.conf"
	echo "# that starts with a '# marble-port: title=' line."
	i=0
	for c in /boot/extlinux/*.conf; do
		[ "$c" = /boot/extlinux/extlinux.conf ] && continue
		t=$(sed -n 's/^# marble-port: title=//p' "$c" | head -1)
		[ -n "$t" ] || continue
		echo "bootmenu_$i=$t=part number scsi 0 esp p; sysboot scsi 0:\${p} any \${pxefile_addr_r} /extlinux/$(basename "$c"); pause"
		i=$((i + 1))
	done
	echo "bootmenu_$i=Back=reset"
} > /boot/extlinux/others.env
sync

# --- 2. root filesystem ------------------------------------------------------
say "formatting $DEV as btrfs"
modprobe btrfs 2>/dev/null || true
umount "$M" 2>/dev/null || true
mkfs.btrfs -q -f -L ALT_ROOT "$DEV"
mkdir -p "$M"
mount -o compress=zstd:3,noatime "$DEV" "$M"
trap 'umount -R "$M" 2>/dev/null || true' EXIT

say "unpacking $(basename "$TARBALL")"
tar --xattrs --xattrs-include='*' --acls --numeric-owner -xpf "$TARBALL" -C "$M"
[ -e "$M/etc/os-release" ] || die "the archive is not a root filesystem (no /etc/os-release)"

# --- 3. device files from postmarketOS ---------------------------------------
say "kernel modules $KVER"
rm -rf "$M/usr/lib/modules/$KVER"
mkdir -p "$M/usr/lib/modules"
cp -a "/lib/modules/$KVER" "$M/usr/lib/modules/"

say "firmware -> /usr/lib/firmware/updates"
mkdir -p "$M/usr/lib/firmware/updates"
cp -a /lib/firmware/. "$M/usr/lib/firmware/updates/"

# ath11k tries board-2.bin before board.bin and the generic WCN6855 one has no
# marble board id, which silently removes all 5 GHz networks.
for b in "$M"/usr/lib/firmware/ath11k/WCN6855/hw2.1/board-2.bin*; do
	case $b in *-disabled) continue ;; esac
	[ -e "$b" ] || [ -L "$b" ] || continue
	mv "$b" "$b.marble-disabled"
	say "disabled generic ath11k $(basename "$b")"
done

say "SSC sensor registry -> /usr/share/qcom"
rm -rf "$M/usr/share/qcom"
cp -a /usr/share/qcom "$M/usr/share/qcom"

say "fstab, hostname, logind"
cat > "$M/etc/fstab" <<EOF
PARTUUID=$PARTUUID	/	btrfs	compress=zstd:3,noatime	0 0
UUID=$ESPUUID	/mnt/pmos-boot	ext2	noauto,nodev,nosuid,noexec	0 0
EOF
echo "xiaomi-marble-alt" > "$M/etc/hostname"
mkdir -p "$M/mnt/pmos-boot" "$M/etc/systemd/logind.conf.d"
cat > "$M/etc/systemd/logind.conf.d/50-marble-powerkey.conf" <<'EOF'
# marble: logind's poweroff default fires before Phosh sees the key, so pressing
# power on a dark screen switched the phone off instead of waking it.
[Login]
HandlePowerKey=ignore
EOF

if [ -d /etc/NetworkManager/system-connections ]; then
	say "Wi-Fi profiles"
	mkdir -p "$M/etc/NetworkManager/system-connections"
	for c in /etc/NetworkManager/system-connections/*.nmconnection; do
		[ -e "$c" ] || continue
		t="$M/etc/NetworkManager/system-connections/$(basename "$c")"
		# interface names differ (wlan0 vs wlp1s0); ath11k can report a zero MAC
		sed -e '/^interface-name=/d' \
		    -e '/^cloned-mac-address=/d' \
		    -e "/^\\[wifi\\]/a cloned-mac-address=$WIFI_MAC" "$c" > "$t"
		chmod 600 "$t"
	done
fi

# --- 4. target setup inside a chroot ----------------------------------------
say "distro setup in a chroot (this needs network access)"
for m in proc sys dev dev/pts; do
	mkdir -p "$M/$m"
	mountpoint -q "$M/$m" || mount --bind "/$m" "$M/$m"
done
[ -e "$M/etc/resolv.conf" ] && mv "$M/etc/resolv.conf" "$M/etc/resolv.conf.marble-backup"
cp /etc/resolv.conf "$M/etc/resolv.conf"
mkdir -p "$M/tmp"
cp "$(dirname "$0")/setup-target.sh" "$M/tmp/setup-target.sh"
chmod 755 "$M/tmp/setup-target.sh"
chroot "$M" /usr/bin/env -i HOME=/root TERM=dumb LANG=C.UTF-8 \
	PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin \
	MP_USER="${MP_USER:-alt}" MP_PASS="$MP_PASS" \
	MP_TOUCHBOOST="${TOUCHBOOST:-}" \
	sh /tmp/setup-target.sh
rm -f "$M/tmp/setup-target.sh"
[ -e "$M/etc/resolv.conf.marble-backup" ] && mv "$M/etc/resolv.conf.marble-backup" "$M/etc/resolv.conf"
for m in dev/pts dev sys proc; do mountpoint -q "$M/$m" && umount -l "$M/$m"; done

if [ -n "${TOUCHBOOST:-}" ] && [ -r "$TOUCHBOOST" ]; then
	mkdir -p "$M/usr/libexec"
	cp "$TOUCHBOOST" "$M/usr/libexec/marble-touchboost"
	chmod 755 "$M/usr/libexec/marble-touchboost"
	say "installed a static marble-touchboost"
fi

sync
say "done: ALT Mobile is installed on $DEV"
say "login: ${MP_USER:-alt} / $MP_PASS${GENERATED_PASS:+  (generated, change it after the first login)}"
cat <<'EOF'

Reboot, hold Volume Down while U-Boot starts, and pick
"Other systems..." -> "ALT Mobile Sisyphus".

The panel stays dark for a second or two while marble-panel-on.service cycles
the framebuffer; that is expected. postmarketOS remains the default entry.
EOF
